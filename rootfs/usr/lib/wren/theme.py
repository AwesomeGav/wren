#!/usr/bin/env python3
"""Wren theme generator.

  wren-theme ensure            write theme files if they're missing (runs at login)
  wren-theme apply             rewrite theme files from ~/.config/wren/theme.json and reload
  wren-theme set MODE ACCENT   e.g. wren-theme set light sky
  wren-theme panel             rewrite only the taskbar config and restart it
  wren-theme wm                rewrite only the window manager config (Wayfire reloads it)
"""
import glob
import json
import os
import shutil
import subprocess
import sys
from string import Template

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from wrenlib import ACCENTS, ICON_ACCENT, THEME_FILE, load_theme, palette, wallpaper, wallpaper_blur  # noqa: E402

HOME = os.path.expanduser("~")
CFG = os.path.join(HOME, ".config")
OUT = os.path.join(CFG, "wren", "theme")
SHARE = "/usr/share/wren"
PREFS = os.path.join(CFG, "wren", "settings.json")
ICON_SRC = "/usr/share/icons/Wren"
WAYBAR_BASE = "/etc/xdg/wren/waybar/config.jsonc"
THEME_VERSION = 7  # bump when the generated files change, so every account picks them up


def rgb(hexstr):
    h = hexstr.lstrip("#")
    return f"{int(h[0:2], 16)}, {int(h[2:4], 16)}, {int(h[4:6], 16)}"


def template_vars(pal):
    v = {k: val for k, val in pal.items() if isinstance(val, str)}
    for k, val in list(v.items()):
        if val.startswith("#"):
            v[k + "_rgb"] = rgb(val)
            v[k + "_hex"] = val.lstrip("#")
    return v


def palette_css(pal):
    """@define-color lines for GTK 3 and GTK 4 (Wren names + standard libadwaita names)."""
    w = {
        "wren_accent": pal["accent"], "wren_accent_hover": pal["accent_hover"], "wren_accent_text": pal["accent_text"],
        "wren_on_accent": pal["on_accent"], "wren_bg": pal["bg"], "wren_window": pal["window"],
        "wren_surface": pal["surface"], "wren_surface2": pal["surface2"], "wren_deep": pal["deep"],
        "wren_border": pal["border"], "wren_border2": pal["border2"], "wren_line": pal["line"],
        "wren_text": pal["text"], "wren_text2": pal["text2"], "wren_dim": pal["dim"], "wren_muted": pal["muted"],
        "wren_danger": pal["danger"],
        "wren_glass": pal["glass"], "wren_glass_strong": pal["glass_strong"], "wren_glass_hover": pal["glass_hover"],
        "wren_glass_border": pal["glass_border"], "wren_glass_edge": pal["glass_edge"],
        "wren_glass_tint": pal["glass_tint"], "wren_shadow": pal["shadow"], "wren_accent_glass": pal["accent_glass"],
        "accent_color": pal["accent_text"], "accent_bg_color": pal["accent"], "accent_fg_color": pal["on_accent"],
        "destructive_bg_color": pal["danger"], "destructive_fg_color": "#FFFFFF",
        "window_bg_color": pal["window"], "window_fg_color": pal["text"],
        "view_bg_color": pal["bg"], "view_fg_color": pal["text"],
        "headerbar_bg_color": pal["surface2"] if pal["scheme"] == "dark" else pal["window"],
        "headerbar_fg_color": pal["text"], "headerbar_backdrop_color": pal["window"],
        "sidebar_bg_color": pal["deep"], "sidebar_fg_color": pal["text"], "sidebar_backdrop_color": pal["deep"],
        "secondary_sidebar_bg_color": pal["deep"], "secondary_sidebar_fg_color": pal["text"],
        "card_bg_color": pal["surface"], "card_fg_color": pal["text"],
        "dialog_bg_color": pal["surface2"] if pal["scheme"] == "dark" else pal["surface"],
        "dialog_fg_color": pal["text"],
        "popover_bg_color": pal["surface2"] if pal["scheme"] == "dark" else pal["surface"],
        "popover_fg_color": pal["text"],
        "thumbnail_bg_color": pal["surface2"], "thumbnail_fg_color": pal["text"],
    }
    lines = ["/* Generated by wren-theme. */"]
    lines += [f"@define-color {k} {v};" for k, v in w.items()]
    return "\n".join(lines) + "\n"


def root_vars(pal):
    dark = pal["scheme"] == "dark"
    pairs = {
        "--accent-color": pal["accent_text"], "--accent-bg-color": pal["accent"], "--accent-fg-color": pal["on_accent"],
        "--destructive-bg-color": pal["danger"], "--window-bg-color": pal["window"], "--window-fg-color": pal["text"],
        "--view-bg-color": pal["bg"], "--view-fg-color": pal["text"],
        "--headerbar-bg-color": pal["surface2"] if dark else pal["window"], "--headerbar-fg-color": pal["text"],
        "--headerbar-backdrop-color": pal["window"], "--sidebar-bg-color": pal["deep"],
        "--sidebar-fg-color": pal["text"], "--sidebar-backdrop-color": pal["deep"],
        "--secondary-sidebar-bg-color": pal["deep"], "--card-bg-color": pal["surface"],
        "--dialog-bg-color": pal["surface2"] if dark else pal["surface"],
        "--popover-bg-color": pal["surface2"] if dark else pal["surface"], "--thumbnail-bg-color": pal["surface2"],
    }
    return ":root {\n" + "".join(f"  {k}: {v};\n" for k, v in pairs.items()) + "}\n"


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, path)


def fill(template_path, values):
    return Template(open(template_path).read()).safe_substitute(values)


def prefs():
    try:
        return json.load(open(PREFS))
    except (OSError, ValueError):
        return {}


def panel_config(pal):
    cfg = json.load(open(WAYBAR_BASE))
    p = prefs()
    if p.get("panel_position") == "top":
        cfg["position"] = "top"
        cfg.pop("margin-bottom", None)
        cfg["margin-top"] = 10
    if p.get("clock_24h"):
        cfg.setdefault("clock", {})["format"] = "{:%a %d   %H:%M}"
    return json.dumps(cfg, indent=2, ensure_ascii=False) + "\n"


def accent_icons(theme):
    """Copy of the Wren icon theme with the accent color swapped in."""
    if theme["accent"] == "sky":
        return "Wren"
    # A differently named theme per accent, so apps notice the change and reload icons
    name = "Wren-" + theme["accent"].title()
    dest = os.path.join(HOME, ".local", "share", "icons", name)
    acc = ACCENTS[theme["accent"]][0]
    for src in glob.glob(ICON_SRC + "/**/*", recursive=True):
        rel = os.path.relpath(src, ICON_SRC)
        out = os.path.join(dest, rel)
        if os.path.isdir(src):
            os.makedirs(out, exist_ok=True)
        elif src.endswith(".svg"):
            write(out, open(src).read().replace(ICON_ACCENT, acc).replace(ICON_ACCENT.lower(), acc))
        elif rel == "index.theme":
            write(out, open(src).read().replace("Name=Wren", "Name=" + name))
        else:
            os.makedirs(os.path.dirname(out), exist_ok=True)
            shutil.copyfile(src, out)
    return name


def quiet(cmd, background=False):
    try:
        if background:
            subprocess.Popen(cmd, start_new_session=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        else:
            subprocess.run(cmd, capture_output=True, timeout=10)
    except (OSError, subprocess.SubprocessError):
        pass


def gset(key, value, schema="org.gnome.desktop.interface"):
    quiet(["gsettings", "set", schema, key, value])


def _keyboard_default():
    lay, var = "us", ""
    try:
        for line in open("/etc/xdg/labwc/environment"):
            k, _, v = line.strip().partition("=")
            if k == "XKB_DEFAULT_LAYOUT":
                lay = v.strip("'\"") or lay
            elif k == "XKB_DEFAULT_VARIANT":
                var = v.strip("'\"")
    except OSError:
        pass
    return lay, var


def _floats(hexstr, alpha):
    h = hexstr.lstrip("#")
    return " ".join(f"{int(h[i:i + 2], 16) / 255:.3f}" for i in (0, 2, 4)) + f" {alpha}"


def wm_config(theme=None, pal=None):
    """The Wayfire config: colors, animations, and mouse/keyboard settings from Settings."""
    theme = theme or load_theme()
    pal = pal or palette(theme)
    p = prefs()
    yn = lambda b: "true" if b else "false"  # noqa: E731
    lay, var = _keyboard_default()
    if p.get("keyboard"):
        lay, _, var = str(p["keyboard"]).partition(":")
    anim = bool(theme["animations"])
    vals = {
        # Wayfire reads "#" as the start of a comment, so colors are written as "r g b a"
        "bg_wf": _floats(pal["bg"], 1.0), "text_wf": _floats(pal["text"], 1.0), "window_wf": _floats(pal["window"], 1.0),
        "snap_fill": _floats(pal["accent"], 0.22), "snap_border": _floats(pal["accent"], 0.8),
        "xkb_layout": lay, "xkb_variant": var,
        "repeat_rate": int(p.get("repeat_rate", 25)), "repeat_delay": int(p.get("repeat_delay", 600)),
        "mouse_speed": f'{float(p.get("mouse_speed", 0.0)):.2f}', "mouse_natural": yn(p.get("mouse_natural", False)),
        "left_handed": yn(p.get("left_handed", False)), "touchpad_natural": yn(p.get("touchpad_natural", True)),
        "tap_to_click": yn(p.get("tap_to_click", True)), "dwt": yn(p.get("dwt", True)),
        "touchpad_speed": f'{float(p.get("touchpad_speed", 0.0)):.2f}', "cursor_size": int(p.get("cursor_size", 24)),
        "open_anim": "zoom" if anim else "none", "close_anim": "zoom" if anim else "none",
        "min_anim": "squeezimize" if anim else "none", "grid_anim": "crossfade" if anim else "none",
    }
    text = fill(f"{SHARE}/templates/wayfire.ini", vals)
    path = os.path.join(CFG, "wren", "wayfire.ini")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    try:
        if open(path).read() == text:
            return path
    except OSError:
        pass
    # Written in place (same file), so the running Wayfire notices and reloads it
    with open(path, "w") as f:
        f.write(text)
    return path


def apply_settings(theme, pal, icons):
    """Light/dark, accent, icons and animations for GNOME and GTK 3 apps."""
    light = theme["mode"] == "light"
    gset("color-scheme", "prefer-light" if light else "prefer-dark")
    gset("gtk-theme", "adw-gtk3" if light else "adw-gtk3-dark")
    gset("icon-theme", icons)
    gset("cursor-theme", "Wren-Cursor")
    gset("accent-color", pal["adw_accent"])
    gset("enable-animations", "true" if theme["animations"] else "false")
    gset("style-variant", "light" if light else "dark", "org.gnome.TextEditor")
    gset("style-scheme", "Adwaita" if light else "wren-dark", "org.gnome.TextEditor")


def generate(reload=False):
    theme = load_theme()
    pal = palette(theme)
    vals = template_vars(pal)
    vals["wallpaper"] = wallpaper()
    vals["wallpaper_blur"] = wallpaper_blur()
    face = os.path.join(HOME, ".face")
    vals["avatar"] = face if os.path.exists(face) else f"{SHARE}/avatar.png"
    vals["clock_fmt"] = "%H:%M" if prefs().get("clock_24h") else "%-I:%M"
    try:
        import pwd
        name = (pwd.getpwuid(os.getuid()).pw_gecos.split(",")[0] or pwd.getpwuid(os.getuid()).pw_name)
    except Exception:
        name = os.environ.get("USER", "")
    vals["USER_NAME"] = name.replace("<", "").replace(">", "")
    vals["name_shift"] = str(min(200, len(name) * 5 + 22))
    vals["glass_rgb"] = "255, 255, 255" if pal["scheme"] == "light" else "30, 34, 42"
    write(os.path.join(OUT, "palette.css"), palette_css(pal))
    write(os.path.join(CFG, "gtk-4.0", "gtk.css"),
          f'/* Generated by wren-theme. */\n@import url("file://{OUT}/palette.css");\n'
          f'@import url("file://{SHARE}/gtk4-rules.css");\n' + root_vars(pal))
    write(os.path.join(CFG, "gtk-3.0", "gtk.css"),
          f'/* Generated by wren-theme. */\n@import url("file://{OUT}/palette.css");\n'
          f'@import url("file://{SHARE}/gtk3-rules.css");\n')
    write(os.path.join(OUT, "waybar.css"), fill(f"{SHARE}/templates/waybar.css", vals))
    write(os.path.join(OUT, "waybar.jsonc"), panel_config(pal))
    write(os.path.join(OUT, "mako"), fill(f"{SHARE}/templates/mako", vals))
    write(os.path.join(OUT, "hyprlock.conf"), fill(f"{SHARE}/templates/hyprlock.conf", vals))
    write(os.path.join(CFG, "labwc", "themerc-override"), fill(f"{SHARE}/templates/themerc-override", vals))
    wm_config(theme, pal)
    icons = accent_icons(theme)
    with open(os.path.join(OUT, "stamp"), "w") as f:
        f.write(json.dumps(dict(theme, v=THEME_VERSION)))

    if reload:
        apply_settings(theme, pal, icons)
        quiet(["labwc", "--reconfigure"])
        quiet(["makoctl", "reload"])
        quiet(["wren-panel"], background=True)
    return theme


def make_blur():
    """Blurred copy of a custom wallpaper photo (Wren's own wallpapers ship one)."""
    w = wallpaper()
    if w.endswith(".jpg") and os.path.exists(w[:-4] + "-blur.jpg"):
        return
    out = os.path.join(HOME, ".cache", "wren", "wallpaper-blur.jpg")
    try:
        from PIL import Image, ImageFilter
        im = Image.open(w).convert("RGB")
        im.thumbnail((960, 960))
        im = im.filter(ImageFilter.GaussianBlur(28))
        os.makedirs(os.path.dirname(out), exist_ok=True)
        im.resize((im.width * 2, im.height * 2), Image.BICUBIC).save(out + ".tmp.jpg", quality=82)
        os.replace(out + ".tmp.jpg", out)
    except Exception:
        pass


def set_theme(mode=None, accent=None, animations=None):
    try:
        t = json.load(open(THEME_FILE))
    except (OSError, ValueError):
        t = {}
    if mode:
        t["mode"] = mode
    if accent:
        t["accent"] = accent
    if animations is not None:
        t["animations"] = bool(animations)
    os.makedirs(os.path.dirname(THEME_FILE), exist_ok=True)
    write(THEME_FILE, json.dumps(t, indent=2) + "\n")
    return generate(reload=True)


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "apply"
    if cmd == "ensure":
        stamp = os.path.join(OUT, "stamp")
        try:
            current = json.load(open(stamp)).get("v") == THEME_VERSION
        except (OSError, ValueError, AttributeError):
            current = False
        if not current or not os.path.exists(os.path.join(CFG, "labwc", "themerc-override")):
            t = generate(reload=False)
            p = palette(t)
            apply_settings(t, p, "Wren" if t["accent"] == "sky" else "Wren-" + t["accent"].title())
            if os.environ.get("LABWC_PID"):
                quiet(["labwc", "--reconfigure"])
    elif cmd == "blur":
        make_blur()
    elif cmd == "wm":
        wm_config()
    elif cmd == "panel":
        write(os.path.join(OUT, "waybar.jsonc"), panel_config(palette(load_theme())))
        quiet(["wren-panel"], background=True)
    elif cmd == "set" and len(sys.argv) >= 4:
        set_theme(sys.argv[2], sys.argv[3])
    else:
        generate(reload=True)
